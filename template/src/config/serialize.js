// Turns a client config object into the source of src/config/client.config.js.
// Used by the builder website and scripts/make-client.mjs.
//
// vite.config.js imports this file in Node, so client text must never leave
// the data: header text is cut to one line (a line break would end the //
// comment), and the config itself is written as JSON.

import { CONFIG_SCHEMA_VERSION } from './resolve.js';

const commentText = value => String(value ?? '')
    .replace(/[\p{Cc}\u2028\u2029\u202A-\u202E\u2066-\u2069]+/gu, ' ').replace(/\s+/g, ' ').trim();

const UNSAFE_KEYS = new Set(['__proto__', 'constructor', 'prototype']);
const plainData = value => (Array.isArray(value) ? value.map(plainData)
    : value && typeof value === 'object'
        ? Object.fromEntries(Object.entries(value).filter(([key]) => !UNSAFE_KEYS.has(key)).map(([key, item]) => [key, plainData(item)]))
        : value);

export function clientConfigSource(config, { generatedAt = '', generator = 'SolarFlow Client Builder' } = {}) {
    if (config?.schemaVersion !== CONFIG_SCHEMA_VERSION) throw new Error(`Config schemaVersion must be ${CONFIG_SCHEMA_VERSION}.`);
    const at = commentText(generatedAt);
    const header = [
        `// ${commentText(config.client?.name) || 'SolarFlow client'} - SolarFlow settings`,
        `// Generated by ${commentText(generator)}${at ? ` on ${at}` : ''}.`,
        '//',
        '// The database keeps its own copy of the features and stages. To change',
        '// them, edit true/false or the stages below, run `npm run setup-sql`, run',
        '// the new backend/setup.sql in the Supabase SQL Editor, then rebuild.',
        '// README.md > "Changing features later" has the details.',
        '// Stage ids (id: ...) are saved on customer records: rename a stage by',
        '// changing its label, never its id.',
        '',
    ].join('\n');
    // U+2028 / U+2029 are valid inside JSON strings; escaped, the file reads the same everywhere.
    const body = JSON.stringify(plainData(config), null, 4).replace(/[\u2028\u2029]/g, ch => `\\u${ch.charCodeAt(0).toString(16)}`);
    return `${header}export default ${body};\n`;
}
