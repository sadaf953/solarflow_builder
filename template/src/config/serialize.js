// Turns a client config object into the source of src/config/client.config.js.
// Used by the builder website and scripts/make-client.mjs.

import { CONFIG_SCHEMA_VERSION } from './resolve.js';

export function clientConfigSource(config, { generatedAt = '', generator = 'SolarFlow Client Builder' } = {}) {
    if (config?.schemaVersion !== CONFIG_SCHEMA_VERSION) throw new Error(`Config schemaVersion must be ${CONFIG_SCHEMA_VERSION}.`);
    const header = [
        `// ${config.client?.name || 'SolarFlow client'} - SolarFlow settings`,
        `// Generated by ${generator}${generatedAt ? ` on ${generatedAt}` : ''}.`,
        '//',
        '// Turn a feature on or off by changing true/false below, then rebuild.',
        '// Stage ids (id: ...) are saved on customer records: rename a stage by',
        '// changing its label, never its id.',
        '',
    ].join('\n');
    return `${header}export default ${JSON.stringify(config, null, 4)};\n`;
}
